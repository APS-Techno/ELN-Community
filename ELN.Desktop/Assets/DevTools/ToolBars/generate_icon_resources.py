def sanitize_name(name):
    """Convert icon name to resource-safe identifier part: uppercase, spaces->underscores."""
    return name.replace(' ', '_').upper()


def copy_tree_node_icons():
    """Verify themed ItemTypes icons exist (generated by generate_itemtype_icons.py)."""
    missing = 0
    for theme in ('Light', 'Dark'):
        theme_dir = os.path.join(THEMED_DIR, theme, 'ItemTypes')
        if not os.path.isdir(theme_dir):
            print(f'  ERROR: {theme}/ItemTypes/ not found — run generate_itemtype_icons.py first')
            missing += 1
            continue
        count = len([f for f in os.listdir(theme_dir) if f.lower().endswith('.png')])
        print(f'  {theme}/ItemTypes/: {count} icons')
    if missing:
        sys.exit(1)
    return 0


def resolve_icon_path(theme, collection, icon_name):
    """
    Find the actual PNG file path for a given theme/collection/icon.

    Source directories per collection:
      ITEM_TB     -> <theme>/Item/
      ITEM_TREE   -> <theme>/ItemTypes/
      PROJECT_TB  -> <theme>/Project/
      PROJECT_TREE-> <theme>/ItemTypes/
      MENU        -> <theme>/Menu/ first, then fallback to <theme>/Item/, <theme>/Project/
    """
    filename = f'{icon_name}.png'

    if collection == 'ITEM_TB':
        return os.path.join(THEMED_DIR, theme, 'Item', filename)
    elif collection == 'ITEM_TREE':
        return os.path.join(THEMED_DIR, theme, 'ItemTypes', filename)
    elif collection == 'PROJECT_TB':
        return os.path.join(THEMED_DIR, theme, 'Project', filename)
    elif collection == 'PROJECT_TREE':
        return os.path.join(THEMED_DIR, theme, 'ItemTypes', filename)
    elif collection == 'FILETYPE':
        if PRIVATE_OUTPUT:
            return os.path.join(TOOLBARS_DIR, 'FileTypes', filename)
        return os.path.join(THEMED_DIR, theme, 'FileTypes', filename)
    elif collection == 'MENU':
        for subdir in ('Menu', 'Item', 'Project'):
            path = os.path.join(THEMED_DIR, theme, subdir, filename)
            if os.path.isfile(path):
                return path
        return os.path.join(THEMED_DIR, theme, 'Menu', filename)
    else:
        raise ValueError(f'Unknown collection: {collection}')


def generate_rc():
    """Generate dm_TreeImages.rc with RCDATA entries for all icon collections."""
    entries = []
    missing = []

    collections = [
        ('ITEM_TB', ITEM_TB_ICONS),
        ('ITEM_TREE', ITEM_TREE_ICONS),
        ('PROJECT_TB', PROJECT_TB_ICONS),
        ('PROJECT_TREE', PROJECT_TREE_ICONS),
        ('MENU', MENU_ICONS),
        ('FILETYPE', FILETYPE_ICONS),
    ]

    for collection_name, icon_list in collections:
        for theme in ('LIGHT', 'DARK'):
            theme_dir_name = theme.capitalize()
            for icon_name in icon_list:
                resource_id = f'{theme}_{collection_name}_{sanitize_name(icon_name)}'
                file_path = resolve_icon_path(theme_dir_name, collection_name, icon_name)

                if not os.path.isfile(file_path):
                    missing.append((resource_id, file_path))
                    continue

                # Forward slashes prevent RC string escapes in Windows paths.
                win_path = os.path.normpath(file_path).replace('\\', '/')
                entries.append(f'{resource_id} RCDATA "{win_path}"')

    if missing:
        print(f'\nWARNING: {len(missing)} missing icon file(s):')
        for res_id, path in missing:
            print(f'  {res_id} -> {path}')

    rc_content = '\n'.join(entries) + '\n'
    with open(RC_FILE, 'w', encoding='utf-8') as f:
        f.write(rc_content)

    print(f'\nGenerated {RC_FILE}')
    print(f'  Total entries: {len(entries)}')
    return len(entries), len(missing)


def compile_rc():
    """Compile resources with the Windows SDK compiler, including long paths."""
    compiler = shutil.which('rc.exe')
    if not compiler:
        sdk_bin = Path(os.environ['ProgramFiles(x86)']) / 'Windows Kits' / '10' / 'bin'
        candidates = sorted(sdk_bin.glob('*/x86/rc.exe'),
                            key=lambda p: tuple(int(n) for n in p.parent.parent.name.split('.')))
        if candidates:
            compiler = str(candidates[-1])
    if not compiler:
        print('ERROR: Windows SDK rc.exe not found')
        sys.exit(1)

    print(f'\nCompiling: {compiler} dm_TreeImages.rc')
    result = subprocess.run(
        [compiler, '/nologo', '/fo', RES_FILE, RC_FILE],
        cwd=VIEWS_DIR,
        capture_output=True,
        text=True,
    )

    if result.stdout:
        print(result.stdout.rstrip())
    if result.stderr:
        print(result.stderr.rstrip())

    if result.returncode != 0:
        print(f'ERROR: rc.exe exited with code {result.returncode}')
        sys.exit(1)

    if os.path.isfile(RES_FILE):
        size_kb = os.path.getsize(RES_FILE) / 1024
        print(f'Output: {RES_FILE} ({size_kb:.1f} KB)')
    else:
        print(f'ERROR: Expected output not found: {RES_FILE}')
        sys.exit(1)


def compile_dll():
    """Wrap dm_TreeImages.res into a resource-only DLL via dcc32."""
    if not os.path.isfile(DCC32):
        print(f'ERROR: dcc32.exe not found at: {DCC32}')
        sys.exit(1)

    dpr_content = "library ELNIcons;\n{$R dm_TreeImages.res}\nbegin\nend.\n"
    with open(DPR_FILE, 'w') as f:
        f.write(dpr_content)

    print(f'\nCompiling: dcc32.exe ELNIcons.dpr')
    result = subprocess.run(
        [DCC32, '-B', '-Q', '-$D-', '-$L-', 'ELNIcons.dpr'],
        cwd=VIEWS_DIR,
        capture_output=True,
        text=True,
    )

    if result.stdout:
        print(result.stdout.rstrip())
    if result.stderr:
        print(result.stderr.rstrip())

    for ext in ('.dpr', '.dcu'):
        tmp = os.path.join(VIEWS_DIR, f'ELNIcons{ext}')
        if os.path.isfile(tmp):
            os.remove(tmp)

    if result.returncode != 0:
        print(f'ERROR: dcc32 exited with code {result.returncode}')
        sys.exit(1)

    if os.path.isfile(DLL_FILE):
        size_kb = os.path.getsize(DLL_FILE) / 1024
        print(f'Output: {DLL_FILE} ({size_kb:.1f} KB)')

        os.makedirs(DEPLOY_DIR, exist_ok=True)
        deploy_path = os.path.join(DEPLOY_DIR, 'ELNIcons.dll')
        if os.path.abspath(DLL_FILE) != os.path.abspath(deploy_path):
            shutil.copy2(DLL_FILE, deploy_path)
        print(f'Deployed: {deploy_path}')
    else:
        print(f'ERROR: Expected output not found: {DLL_FILE}')
        sys.exit(1)


def copy_filetype_icons():
    """Copy FileTypes PNGs into both Light/FileTypes/ and Dark/FileTypes/ (single-theme icons)."""
    src_dir = os.path.join(TOOLBARS_DIR, 'FileTypes')
    if not os.path.isdir(src_dir):
        print(f'  ERROR: FileTypes/ source directory not found')
        sys.exit(1)
    copied = 0
    for theme in ('Light', 'Dark'):
        dst_dir = os.path.join(TOOLBARS_DIR, theme, 'FileTypes')
        os.makedirs(dst_dir, exist_ok=True)
        for icon_name in FILETYPE_ICONS:
            src = os.path.join(src_dir, f'{icon_name}.png')
            dst = os.path.join(dst_dir, f'{icon_name}.png')
            if os.path.isfile(src):
                shutil.copy2(src, dst)
                copied += 1
            else:
                print(f'  WARNING: Missing {src}')
    print(f'  Copied {copied} file type icons to Light/Dark directories')


def generate_private_icons():
    """Render existing icon definitions without changing source assets."""
    sys.dont_write_bytecode = True
    import generate_toolbar_icons as toolbar
    import generate_itemtype_icons as itemtypes
    import generate_menu_icons as menu

    groups = [
        (toolbar, 'Item', ITEM_TB_ICONS),
        (toolbar, 'Project', PROJECT_TB_ICONS),
        (itemtypes, 'ItemTypes', list(itemtypes.ICONS)),
        (menu, 'Menu', list(menu.ICONS)),
    ]
    for generator, collection, names in groups:
        for theme, palette in generator.PALETTES.items():
            directory = os.path.join(THEMED_DIR, theme, collection)
            os.makedirs(directory, exist_ok=True)
            for name in names:
                generator.ICONS[name](palette).save(os.path.join(directory, name + '.png'))


def main():
    global VIEWS_DIR, RC_FILE, RES_FILE, DEPLOY_DIR, DLL_FILE, DPR_FILE, PRIVATE_OUTPUT, THEMED_DIR, DCC32
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output-dir', help='Build and deploy only in this directory')
    parser.add_argument('--dcc32', required=True, help='Path to the configured Delphi Win32 compiler')
    args = parser.parse_args()
    DCC32 = os.path.abspath(args.dcc32)
    if args.output_dir:
        PRIVATE_OUTPUT = True
        VIEWS_DIR = os.path.abspath(args.output_dir)
        os.makedirs(VIEWS_DIR, exist_ok=True)
        RC_FILE = os.path.join(VIEWS_DIR, 'dm_TreeImages.rc')
        RES_FILE = os.path.join(VIEWS_DIR, 'dm_TreeImages.res')
        DEPLOY_DIR = VIEWS_DIR
        DLL_FILE = os.path.join(VIEWS_DIR, 'ELNIcons.dll')
        DPR_FILE = os.path.join(VIEWS_DIR, 'ELNIcons.dpr')
        THEMED_DIR = os.path.join(VIEWS_DIR, 'Images')
        generate_private_icons()
    print('=== ELN3 Icon Resource Generator ===\n')

    print('Step 1: Checking themed ItemTypes icons...')
    copy_tree_node_icons()
    print()

    if not PRIVATE_OUTPUT:
        print('Step 1b: Copying FileTypes icons to themed directories...')
        copy_filetype_icons()
        print()

    print('Step 2: Generating dm_TreeImages.rc...')
    entry_count, missing_count = generate_rc()

    if missing_count > 0:
        print(f'\nAborting: {missing_count} missing icon(s). Fix the above before compiling.')
        sys.exit(1)

    print('\nStep 3: Compiling .rc -> .res...')
    compile_rc()

    print('\nStep 4: Building resource-only DLL...')
    compile_dll()

    print('\nDone!')


if __name__ == '__main__':
    main()
